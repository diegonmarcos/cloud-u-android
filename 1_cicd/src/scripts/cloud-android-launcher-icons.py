#!/usr/bin/env python3
"""Fleet launcher icons: ONE generator, ONE pattern, declared once.

Every fleet app's Android launcher icon is generated from
  * 1_cicd/src/data/launcher-icons.json  -- the pattern (glyph placement, cloud
    badge, gradient), the category colours and the glyph library;
  * <app>/build.json::launcher_icon       -- the app's {glyph, category}, where
    its res dir is (`res`), and optionally `aliases` (activity-alias icons that
    get the same generated icon), `legacy` (also a pre-API-26 layer-list) and
    `tile` (the SuperApp drawable that carries the plain glyph for the
    Cloud page tile).

Usage:
  cloud-android-launcher-icons.py            write every generated file, delete
                                             hand-made launcher art it replaces
  cloud-android-launcher-icons.py --check    fail (exit 1) on any drift: the guard
  cloud-android-launcher-icons.py --sheet P  render a contact sheet PNG (needs cairosvg)
"""
import json
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.realpath(__file__)), "..", "..", ".."))
if not os.path.isfile(os.path.join(ROOT, "1_cicd/src/data/launcher-icons.json")):
    ROOT = os.getcwd()
DATA = "1_cicd/src/data/launcher-icons.json"
SUPERAPP = "aa_cloud-superapp"
TILE_DIR = SUPERAPP + "/app/src/main/res/drawable"
HEADER = ("<!-- GENERATED by 1_cicd/src/scripts/cloud-android-launcher-icons.py from "
          "1_cicd/src/data/launcher-icons.json + %s/build.json::launcher_icon "
          "(glyph %s, category %s). Do not edit: change the declaration and regenerate. -->\n")
# Old launcher art that an adaptive icon used to reference under a non-standard name.
FOREIGN_ART = re.compile(r"^(ic_launcher_.*|ic_acode_.*|ic_webserver_fg|ic_media_fg)$")


def load(p):
    with open(os.path.join(ROOT, p), encoding="utf-8") as f:
        return json.load(f)


def fleet_apps():
    """Directories of the Store's `apps` group (aa_cloud-superapp/data/constellation-fleet.json)."""
    fleet = load(SUPERAPP + "/data/constellation-fleet.json")
    members = next(g for g in fleet["groups"] if g["id"] == "apps")["members"]
    out = []
    for m in members:
        for d in (m, "ac_cloud-" + m, "ac_c3-" + m):
            if os.path.isfile(os.path.join(ROOT, d, "build.json")):
                out.append(d)
                break
        else:
            raise SystemExit("fleet member %r has no app directory" % m)
    return out


def gpath(cfg, gid):
    g = cfg["glyphs"][gid]
    return g["path"] if isinstance(g, dict) else g


def gfill(cfg, gid):
    g = cfg["glyphs"][gid]
    return ' android:fillType="%s"' % g["fill_type"] if isinstance(g, dict) and g.get("fill_type") else ""


def fmt(n):
    return ("%g" % n)


def fg_xml(app, li, cfg):
    p = cfg["pattern"]; g = p["glyph"]; b = p["badge"]; v = fmt(p["viewport"])
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n' + HEADER % (app, li["glyph"], li["category"]) +
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="%sdp" android:height="%sdp"\n'
        '    android:viewportWidth="%s" android:viewportHeight="%s">\n' % (v, v, v, v) +
        '    <group android:scaleX="%s" android:scaleY="%s" android:translateX="%s" android:translateY="%s">\n'
        % (fmt(g["scale"]), fmt(g["scale"]), fmt(g["translate_x"]), fmt(g["translate_y"])) +
        '        <path android:fillColor="%s"%s android:pathData="%s" />\n' % (g["fill"], gfill(cfg, li["glyph"]), gpath(cfg, li["glyph"])) +
        '    </group>\n'
        '    <group android:scaleX="%s" android:scaleY="%s" android:translateX="%s" android:translateY="%s">\n'
        % (fmt(b["scale"]), fmt(b["scale"]), fmt(b["translate_x"]), fmt(b["translate_y"])) +
        '        <path android:fillColor="%s" android:pathData="%s" />\n' % (b["fill"], b["path"]) +
        '    </group>\n'
        '</vector>\n')


def mono_xml(app, li, cfg):
    p = cfg["pattern"]; g = p["glyph"]; v = fmt(p["viewport"])
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n' + HEADER % (app, li["glyph"], li["category"]) +
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="%sdp" android:height="%sdp"\n'
        '    android:viewportWidth="%s" android:viewportHeight="%s">\n' % (v, v, v, v) +
        '    <group android:scaleX="%s" android:scaleY="%s" android:translateX="%s" android:translateY="%s">\n'
        % (fmt(g["scale"]), fmt(g["scale"]), fmt(g["translate_x"]), fmt(g["translate_y"])) +
        '        <path android:fillColor="#FF000000"%s android:pathData="%s" />\n' % (gfill(cfg, li["glyph"]), gpath(cfg, li["glyph"])) +
        '    </group>\n'
        '</vector>\n')


def bg_xml(app, li, cfg):
    p = cfg["pattern"]; gr = p["gradient"]; c = cfg["categories"][li["category"]]; v = fmt(p["viewport"])
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n' + HEADER % (app, li["glyph"], li["category"]) +
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    xmlns:aapt="http://schemas.android.com/aapt"\n'
        '    android:width="%sdp" android:height="%sdp"\n'
        '    android:viewportWidth="%s" android:viewportHeight="%s">\n' % (v, v, v, v) +
        '    <path android:pathData="M0,0h%sv%sh-%sz">\n' % (v, v, v) +
        '        <aapt:attr name="android:fillColor">\n'
        '            <gradient android:type="linear"\n'
        '                android:startX="%s" android:startY="%s" android:endX="%s" android:endY="%s"\n'
        % (fmt(gr["start_x"]), fmt(gr["start_y"]), fmt(gr["end_x"]), fmt(gr["end_y"])) +
        '                android:startColor="%s" android:endColor="%s" />\n' % (c["start"], c["end"]) +
        '        </aapt:attr>\n'
        '    </path>\n'
        '</vector>\n')


def adaptive_xml(app, li):
    return ('<?xml version="1.0" encoding="utf-8"?>\n' + HEADER % (app, li["glyph"], li["category"]) +
            '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
            '    <background android:drawable="@drawable/ic_launcher_background" />\n'
            '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
            '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
            '</adaptive-icon>\n')


def legacy_xml(app, li):
    return ('<?xml version="1.0" encoding="utf-8"?>\n' + HEADER % (app, li["glyph"], li["category"]) +
            '<!-- Pre-API-26 fallback: the same two layers, flattened. API 26+ uses mipmap-anydpi-v26. -->\n'
            '<layer-list xmlns:android="http://schemas.android.com/apk/res/android">\n'
            '    <item android:drawable="@drawable/ic_launcher_background" />\n'
            '    <item android:drawable="@drawable/ic_launcher_foreground" />\n'
            '</layer-list>\n')


def tile_xml(app, li, cfg):
    return ('<?xml version="1.0" encoding="utf-8"?>\n' + HEADER % (app, li["glyph"], li["category"]) +
            '<!-- The plain glyph of %s\'s launcher icon, for its SuperApp Cloud tile. -->\n' % app +
            '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:width="24dp" android:height="24dp"\n'
            '    android:viewportWidth="24" android:viewportHeight="24"\n'
            '    android:tint="?attr/colorOnSurface">\n'
            '    <path android:fillColor="@android:color/white"%s android:pathData="%s" />\n' % (gfill(cfg, li["glyph"]), gpath(cfg, li["glyph"])) +
            '</vector>\n')


COLOR_RE = re.compile(r'(<color name="ic_launcher_background">)[^<]*(</color>)')


def plan(cfg):
    """{path: content} to write, [paths] to delete, [errors]."""
    write, delete, errors = {}, [], []
    apps = fleet_apps()
    exempt = cfg.get("exempt", {})
    seen_glyph = {}
    seen_path = {}
    for app in apps:
        if app in exempt:
            continue
        bj = load(app + "/build.json")
        li = bj.get("launcher_icon")
        if not isinstance(li, dict):
            errors.append("%s/build.json declares no launcher_icon {glyph, category, res}" % app)
            continue
        if li.get("category") not in cfg["categories"]:
            errors.append("%s: launcher_icon.category %r is not one of %s" % (app, li.get("category"), sorted(cfg["categories"])))
            continue
        if li.get("glyph") not in cfg["glyphs"]:
            errors.append("%s: launcher_icon.glyph %r is not in %s glyphs" % (app, li.get("glyph"), DATA))
            continue
        if li["glyph"] in seen_glyph:
            errors.append("%s and %s both declare glyph %r: every app needs its own symbol" % (seen_glyph[li["glyph"]], app, li["glyph"]))
        seen_glyph[li["glyph"]] = app
        pd = gpath(cfg, li["glyph"])
        if pd in seen_path and seen_path[pd] != li["glyph"]:
            errors.append("glyphs %r and %r draw the same path" % (seen_path[pd], li["glyph"]))
        seen_path[pd] = li["glyph"]

        if li.get("res") is None:
            if app not in cfg.get("res_pending", {}):
                errors.append("%s: launcher_icon.res is null and %s::res_pending gives no reason" % (app, DATA))
            continue
        res = os.path.normpath(os.path.join(app, li["res"]))
        if not os.path.isdir(os.path.join(ROOT, res)):
            errors.append("%s: launcher_icon.res %s is not a directory" % (app, res))
            continue
        mine = {
            res + "/drawable/ic_launcher_foreground.xml": fg_xml(app, li, cfg),
            res + "/drawable/ic_launcher_background.xml": bg_xml(app, li, cfg),
            res + "/drawable/ic_launcher_monochrome.xml": mono_xml(app, li, cfg),
        }
        for name in ["ic_launcher", "ic_launcher_round"] + list(li.get("aliases", [])):
            mine[res + "/mipmap-anydpi-v26/%s.xml" % name] = adaptive_xml(app, li)
            if li.get("legacy"):
                mine[res + "/mipmap-anydpi/%s.xml" % name] = legacy_xml(app, li)
        colour = os.path.join(ROOT, res, "values/ic_launcher_background.xml")
        if os.path.isfile(colour):
            text = open(colour, encoding="utf-8").read()
            mine[res + "/values/ic_launcher_background.xml"] = COLOR_RE.sub(
                r"\g<1>%s\g<2>" % cfg["categories"][li["category"]]["start"], text)
        if li.get("tile"):
            mine[TILE_DIR + "/%s.xml" % li["tile"]] = tile_xml(app, li, cfg)
        write.update(mine)

        # Everything else that is launcher art in this res dir (and in sibling
        # source sets that would override it) is hand-made and goes.
        roots = [res]
        if res.endswith("/src/main/res"):
            src = os.path.join(ROOT, res[: -len("/main/res")])
            roots += [os.path.relpath(os.path.join(src, s, "res"), ROOT) for s in sorted(os.listdir(src))
                      if s != "main" and os.path.isdir(os.path.join(src, s, "res"))]
        for r in roots:
            for d in sorted(os.listdir(os.path.join(ROOT, r))):
                full = os.path.join(ROOT, r, d)
                if not os.path.isdir(full):
                    continue
                for f in sorted(os.listdir(full)):
                    rel = "%s/%s/%s" % (r, d, f)
                    stem = f.split(".")[0]
                    if rel in mine:
                        continue
                    if (d.startswith("mipmap") or d.startswith("drawable")) and FOREIGN_ART.match(stem):
                        delete.append(rel)
    return write, delete, errors


def cloud_page_checks(cfg):
    """Category vs SuperApp Cloud groups; plain Cloud-page icons are unique."""
    errors = []
    bj = load(SUPERAPP + "/build.json")
    sec = next(s for s in bj["ui"]["sections"] if s.get("id") == "cloud")
    by_title = {c["tile_group"]: k for k, c in cfg["categories"].items()}
    icons = {}
    for g in sec.get("tile_groups", []):
        for t in g.get("tiles", []):
            if t.get("separator"):
                continue
            tgt = (t.get("target") or "").split("#")[0]
            icon = t.get("icon")
            if icon:
                prev = icons.get(icon)
                if prev and prev[1] != tgt:
                    errors.append("Cloud page: %r (%s) and %r (%s) share the plain icon %s" % (prev[0], prev[2], t.get("label"), g["title"], icon))
                icons.setdefault(icon, (t.get("label"), tgt, g["title"]))
            m = re.match(r"^extapp:(cloud-[\w-]+)$", tgt)
            if m and g["title"] in by_title and os.path.isfile(os.path.join(ROOT, "ac_" + m.group(1), "build.json")):
                app = "ac_" + m.group(1)
                if app in cfg.get("exempt", {}):
                    continue
                li = load(app + "/build.json").get("launcher_icon") or {}
                if li.get("category") != by_title[g["title"]]:
                    errors.append("%s is listed under the Cloud page's %r group but declares launcher_icon.category %r (want %r)"
                                  % (app, g["title"], li.get("category"), by_title[g["title"]]))
    for t in sec.get("tiles_labs", []):
        icon = t.get("icon")
        if icon in icons and icons[icon][1] != (t.get("target") or "").split("#")[0]:
            errors.append("Cloud page: labs tile %r shares the plain icon %s with %r" % (t.get("label"), icon, icons[icon][0]))
        icons.setdefault(icon, (t.get("label"), (t.get("target") or "").split("#")[0], "labs"))
    return errors


def sheet(cfg, out):
    import cairosvg  # noqa: only for the contact sheet
    p = cfg["pattern"]; g = p["glyph"]; b = p["badge"]
    groups = {}
    for app in fleet_apps():
        li = load(app + "/build.json").get("launcher_icon")
        if app in cfg.get("exempt", {}) or not li:
            continue
        groups.setdefault(li["category"], []).append((app, li))
    cell, size, cols = 150, 108, 9
    rows = sum((len(v) + cols - 1) // cols for v in groups.values())
    W = cols * cell + 40
    H = 40 + len(groups) * 44 + rows * cell
    parts = ['<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d"><rect width="100%%" height="100%%" fill="#0B0B14"/>' % (W, H)]
    y = 20
    for k in cfg["categories"]:
        if k not in groups:
            continue
        c = cfg["categories"][k]
        parts.append('<text x="20" y="%d" font-family="sans-serif" font-size="22" font-weight="bold" fill="%s">%s</text>' % (y + 26, "#E9D5FF", c["label"] + "  " + c["start"] + " → " + c["end"]))
        y += 44
        for i, (app, li) in enumerate(sorted(groups[k])):
            x = 20 + (i % cols) * cell + (cell - size) // 2
            if i and i % cols == 0:
                y += cell
            gid = "g_%s" % re.sub(r"\W", "_", app)
            parts.append('<defs><linearGradient id="%s" gradientUnits="userSpaceOnUse" x1="6" y1="6" x2="102" y2="102"><stop offset="0" stop-color="%s"/><stop offset="1" stop-color="%s"/></linearGradient><clipPath id="c%s"><circle cx="54" cy="54" r="50"/></clipPath></defs>' % (gid, c["start"], c["end"], gid))
            parts.append('<g transform="translate(%d,%d)"><g clip-path="url(#c%s)"><rect width="108" height="108" fill="url(#%s)"/>' % (x, y, gid, gid))
            parts.append('<g transform="translate(%s,%s) scale(%s)"><path fill="#fff" fill-rule="%s" d="%s"/></g>' % (g["translate_x"], g["translate_y"], g["scale"], "evenodd" if gfill(cfg, li["glyph"]) else "nonzero", gpath(cfg, li["glyph"])))
            parts.append('<g transform="translate(%s,%s) scale(%s)"><path fill="#fff" fill-opacity="0.95" d="%s"/></g></g>' % (b["translate_x"], b["translate_y"], b["scale"], b["path"]))
            parts.append('<text x="54" y="128" text-anchor="middle" font-family="sans-serif" font-size="13" fill="#E5E7EB">%s</text></g>' % re.sub(r"^a[ac]_(cloud-|c3-)?", "", app))
        y += cell
    parts.append("</svg>")
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    cairosvg.svg2png(bytestring="".join(parts).encode(), write_to=out)
    print("contact sheet: %s" % out)


def main(argv):
    cfg = load(DATA)
    if "--sheet" in argv:
        sheet(cfg, argv[argv.index("--sheet") + 1])
        return 0
    write, delete, errors = plan(cfg)
    errors += cloud_page_checks(cfg)
    if "--check" in argv:
        for p, text in sorted(write.items()):
            full = os.path.join(ROOT, p)
            if not os.path.isfile(full):
                errors.append("missing generated file %s" % p)
            elif open(full, encoding="utf-8").read() != text:
                errors.append("%s differs from what the generator produces (hand-edited?)" % p)
        for p in delete:
            errors.append("hand-made launcher art outside the generator: %s" % p)
        for e in errors:
            print("FAIL: " + e)
        print("launcher icons: %d generated files checked, %d problems" % (len(write), len(errors)))
        return 1 if errors else 0
    for p, text in write.items():
        full = os.path.join(ROOT, p)
        os.makedirs(os.path.dirname(full), exist_ok=True)
        with open(full, "w", encoding="utf-8") as f:
            f.write(text)
    for p in delete:
        os.remove(os.path.join(ROOT, p))
        d = os.path.dirname(os.path.join(ROOT, p))
        if not os.listdir(d):
            os.rmdir(d)
    for e in errors:
        print("WARN: " + e)
    print("wrote %d files, deleted %d" % (len(write), len(delete)))
    return 1 if errors else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
