#!/usr/bin/env python3
"""#1369 Cloud Notes theme generator: data/obsidian-theme.json -> the web sheet and the native tokens.

  packages/frontend/component/src/theme/obsidian.gen.css   Obsidian's variables + every mapped AFFiNE variable, light and dark
  packages/frontend/apps/android/App/app/src/main/java/app/cloudnotes/pro/theme/ObsidianTokens.kt   the native colour schemes

Usage: gen-obsidian-theme.py [--check] [--src <json>]. --check exits 1 when a generated file differs (test/test-obsidian-theme.sh).
"""
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'data', 'obsidian-theme.json')
CSS_OUT = 'packages/frontend/component/src/theme/obsidian.gen.css'
KT_OUT = 'packages/frontend/apps/android/App/app/src/main/java/app/cloudnotes/pro/theme/ObsidianTokens.kt'
MODES = ('light', 'dark')
HEADER = 'GENERATED by ac_cloud-notes/scripts/gen-obsidian-theme.py from ac_cloud-notes/data/obsidian-theme.json. DO NOT EDIT.'


def hex_rgb(h):
    h = h.lstrip('#')
    if len(h) != 6:
        raise ValueError('bad hex ' + h)
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


class Theme:
    def __init__(self, d):
        self.d = d

    def ref(self, name, mode):
        """A ref ('base-30', 'accent', 'accent-1', 'red', '#hex') -> '#rrggbb'."""
        d = self.d
        if name.startswith('#'):
            return name.lower()
        if name.startswith('base-'):
            return d['base'][mode][name[5:]]
        if name in d['accent']:
            v = d['accent'][name]
            return v if isinstance(v, str) else v[mode]
        if name in d['extended'][mode]:
            return d['extended'][mode][name]
        if name in d['semantic']:
            return self.ref(d['semantic'][name][mode], mode)
        raise KeyError('unknown colour ref ' + name)

    def rgba(self, value, mode):
        """'<ref>' or '<ref>@<alpha>' -> (r, g, b, a)."""
        ref, _, alpha = value.partition('@')
        r, g, b = hex_rgb(self.ref(ref, mode))
        return r, g, b, float(alpha) if alpha else 1.0

    def semantic(self, name, mode):
        return self.rgba(self.d['semantic'][name][mode], mode)


def css_color(c):
    r, g, b, a = c
    return '#%02x%02x%02x' % (r, g, b) if a >= 1 else 'rgba(%d, %d, %d, %s)' % (r, g, b, ('%.3f' % a).rstrip('0').rstrip('.'))


def gen_css(t):
    d = t.d
    ty = d['typography']
    out = ['/* ' + HEADER + ' */', '/* Obsidian default theme (#1369): Obsidian names first, then every AFFiNE variable the app paints with, pointed at them. */']
    for mode in MODES:
        sel = ':root,\n[data-theme=light]' if mode == 'light' else '[data-theme=dark]'
        out.append(sel + ' {')
        out.append('  color-scheme: %s;' % mode)
        for k, v in d['base'][mode].items():
            out.append('  --color-base-%s: %s;' % (k, v))
        out.append('  --accent-h: %d;\n  --accent-s: %d%%;\n  --accent-l: %d%%;' % tuple(d['accent_hsl']))
        for k in d['accent']:
            out.append('  --color-%s: %s;' % (k, t.ref(k, mode)))
        for k, v in d['extended'][mode].items():
            out.append('  --color-%s: %s;' % (k, v))
        for k in d['semantic']:
            out.append('  --%s: %s;' % (k, css_color(t.semantic(k, mode))))
        for k in ('link-color', 'link-external-color', 'tag-color'):
            out.append('  --%s: var(--text-accent);' % k)
        for k in ('blockquote-border-color', 'checkbox-color'):
            out.append('  --%s: var(--interactive-accent);' % k)
        if mode == 'light':
            for k in ('font-interface', 'font-text', 'font-monospace'):
                out.append('  --%s: %s;' % (k, ty[k]))
            for k in ('font-text-size', 'font-ui-smaller', 'font-ui-small', 'font-ui-medium', 'font-ui-large'):
                out.append('  --%s: %dpx;' % (k, ty[k]))
            for k in ('line-height-normal', 'line-height-tight'):
                out.append('  --%s: %s;' % (k, ty[k]))
            for k in ('h1', 'h2', 'h3', 'h4', 'h5', 'h6'):
                out.append('  --%s-size: %sem;' % (k, ty[k]))
            for k, v in d['radius'].items():
                out.append('  --%s: %dpx;' % (k, v))
            for k, v in d['affine_typography'].items():
                if not k.startswith('_'):
                    out.append('  --%s: var(--%s);' % (k, v))
        for k, v in d['affine'].items():
            if not k.startswith('_'):
                out.append('  --%s: var(--%s);' % (k, v))
        out.append('}')
    out.append('body {\n  font-family: var(--font-interface);\n  background: var(--background-primary);\n  color: var(--text-normal);\n}')
    out.append('::selection {\n  background: var(--text-selection);\n}')
    return '\n'.join(out) + '\n'


def kt_color(c):
    r, g, b, a = c
    return 'Color(0x%02X%02X%02X%02X)' % (round(a * 255), r, g, b)


def camel(name):
    head, *rest = name.split('-')
    return head + ''.join(p.capitalize() for p in rest)


def gen_kt(t):
    d = t.d
    out = ['// ' + HEADER, 'package app.cloudnotes.pro.theme', '', 'import androidx.compose.ui.graphics.Color', '',
           '/** Obsidian\'s default theme as native colours (#1369): every semantic name, light and dark. */',
           'object ObsidianTokens {']
    for mode in MODES:
        out.append('    object %s {' % mode.capitalize())
        for k in d['semantic']:
            out.append('        val %s = %s' % (camel(k), kt_color(t.semantic(k, mode))))
        out.append('    }')
    out.append('    const val FONT_TEXT_SIZE_SP = %d' % d['typography']['font-text-size'])
    out.append('    const val FONT_UI_SMALL_SP = %d' % d['typography']['font-ui-small'])
    out.append('    const val FONT_UI_MEDIUM_SP = %d' % d['typography']['font-ui-medium'])
    out.append('}')
    for mode in MODES:
        out.append('')
        out.append('val cloudNotes%sScheme = CloudNotesColorScheme(' % mode.capitalize())
        for field, sem in d['native'].items():
            if not field.startswith('_'):
                out.append('    %s = ObsidianTokens.%s.%s,' % (field, mode.capitalize(), camel(sem)))
        out.append(')')
    return '\n'.join(out) + '\n'


def main(argv):
    check = '--check' in argv
    src = argv[argv.index('--src') + 1] if '--src' in argv else SRC
    t = Theme(json.load(open(src, encoding='utf-8')))
    bad = 0
    for rel, text in ((CSS_OUT, gen_css(t)), (KT_OUT, gen_kt(t))):
        path = os.path.join(ROOT, rel)
        cur = open(path, encoding='utf-8').read() if os.path.exists(path) else None
        if check:
            if cur != text:
                print('DRIFT ' + rel)
                bad += 1
        elif cur != text:
            with open(path, 'w', encoding='utf-8') as f:
                f.write(text)
            print('wrote ' + rel)
    return 1 if bad else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
