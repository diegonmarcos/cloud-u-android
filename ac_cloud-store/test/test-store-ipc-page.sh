#!/usr/bin/env bash
# #ipc Cloud Store > Access > IPC: the fleet's IPC Mesh (a0_docs/eng-specs/fleet-ipc.md).
#   S1 build.json::ui access.pages: ipc ("IPC") right after mesh ("Apps Mesh"), 2..8 pages (nav rule)
#   S2 AccessPage routes PAGE_IPC to libs:appstore's shared IpcMeshPage — the composable SuperApp's
#      Configs > Network > IPC draws too; no second copy anywhere in the fleet
#   S3 the page draws exactly IpcMesh.rows (one row per member, and per declared endpoint unfolded),
#      each tagged, so "every declared endpoint is listed" is one function's property
#      (SuperApp IpcMeshPageTest P1/P2 run it on the composed page)
#   S4 the registry is a declared data source: libs:appstore bakes IPC_MESH_B64 from the GENERATED
#      aa_cloud-superapp/data/ipc-mesh.json (1_cicd/src/scripts/cloud-android-ipc-mesh.py; the mesh
#      guard fails when it is stale), and every member in it has its endpoints
#   S5 the live probe only reads the PackageManager; the door's ping is an explicit action
# Then each planted defect must turn it red.
set -u
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
LIB="ab_cloud-libs-shared/libs/appstore"
KT="$LIB/src/main/java/com/diegonmarcos/superapp/appstore"
PASS=0; FAIL=0

check() {  # check <root> -> number of failures (printed)
  local R="$1" f=0
  ok()  { echo "  PASS: $1"; }
  bad() { echo "  FAIL: $1"; f=$((f+1)); }
  local BJ="$R/ac_cloud-store/build.json" AP="$R/ac_cloud-store/app/src/main/java/com/diegonmarcos/cloudstore/AccessPage.kt"
  local PG="$R/$KT/IpcMeshPage.kt" MD="$R/$KT/IpcMesh.kt" GR="$R/$LIB/build.gradle" REG="$R/aa_cloud-superapp/data/ipc-mesh.json"
  for x in "$BJ" "$AP" "$PG" "$MD" "$GR" "$REG"; do [ -f "$x" ] || { bad "missing ${x#$R/}"; return 1; }; done
  python3 - "$BJ" <<'PY' && ok "S1 Access = mesh, ipc, … (IPC after Apps Mesh, 2..8 pages)" || bad "S1 Access pages do not put IPC after Apps Mesh within 2..8"
import json, sys
s = next(s for s in json.load(open(sys.argv[1]))['ui']['sections'] if s['id'] == 'access')
ids = [p['id'] for p in s['pages']]; lab = {p['id']: p['label'] for p in s['pages']}
sys.exit(0 if 'ipc' in ids and ids.index('ipc') == ids.index('mesh') + 1 and lab['ipc'] == 'IPC' and 2 <= len(ids) <= 8 else 1)
PY
  grep -q 'const val PAGE_IPC = "ipc"' "$AP" && grep -q 'PAGE_IPC -> IpcMeshPage()' "$AP" \
    && ok "S2 AccessPage routes ipc to the shared IpcMeshPage" || bad "S2 AccessPage does not route ipc to IpcMeshPage"
  local copies; copies="$(grep -rl --include=*.kt 'fun IpcMeshPage(' "$R"/a[abc]_* 2>/dev/null | grep -v '/test/' | wc -l)"
  [ "$copies" = 1 ] && ok "S2 one IpcMeshPage in the fleet" || bad "S2 $copies IpcMeshPage definitions (one shared composable only)"
  grep -q 'for (row in IpcMesh.rows(reg, live, filter, expanded, expandAll, order))' "$PG" \
    && grep -q 'testTag(row.tag)' "$PG" && grep -q 'tag = row.tag' "$PG" \
    && ok "S3 the page draws exactly IpcMesh.rows, each row tagged" || bad "S3 the page does not draw IpcMesh.rows row by row"
  grep -q 'm.endpoints.map { Row(TAG_ENDPOINT + key(m, it), m, it) }' "$MD" \
    && ok "S3 an unfolded member yields a row per declared endpoint" || bad "S3 rows() drops endpoints"
  grep -q 'new File(constellationFleetFile.parentFile, "ipc-mesh.json")' "$GR" && grep -q '"IPC_MESH_B64",.*bakeB64(ipcMeshB64)' "$GR" \
    && ok "S4 libs:appstore bakes the generated registry" || bad "S4 the registry is not baked from data/ipc-mesh.json"
  python3 - "$REG" <<'PY' && ok "S4 the registry is generated and every member has endpoints" || bad "S4 registry hand-edited, empty, or a member without endpoints"
import json, sys
d = json.load(open(sys.argv[1]))
assert d["_doc"].startswith("GENERATED by 1_cicd/src/scripts/cloud-android-ipc-mesh.py")
for m in d["members"]:
    n = len(m["endpoints"]) + sum(len(d["shared"][l]) for l in m["libs"])
    assert n > 0 or not m["door"], m["id"]
PY
  local probe; probe="$(awk '/fun probe\(/{f=1} f{print} f&&/^    }$/{exit}' "$MD")"
  printf '%s' "$probe" | grep -q 'FleetIpc.ping\|FleetIpc.call' && bad "S5 the passive probe asks the door (it would start every member)" \
    || ok "S5 the passive probe reads the PackageManager only"
  grep -q 'StoreAction(looks.action, "Ping doors", Modifier.weight(1f)) { pingAll() }' "$PG" && ok "S5 the door's ping is an explicit action" || bad "S5 no Ping doors action"
  return $f
}

out="$(check "$ROOT")"; rc=$?; printf '%s\n' "$out"
PASS=$(printf '%s\n' "$out" | grep -c '  PASS:'); FAIL=$rc

# planted defects: each must turn the check red
TMP="$(mktemp -d)"; trap 'rm -rf "$TMP"' EXIT
mirror() {
  rm -rf "$TMP/r"; mkdir -p "$TMP/r"
  for d in ac_cloud-store/build.json ac_cloud-store/app/src/main/java/com/diegonmarcos/cloudstore/AccessPage.kt \
           "$KT/IpcMeshPage.kt" "$KT/IpcMesh.kt" "$LIB/build.gradle" aa_cloud-superapp/data/ipc-mesh.json; do
    mkdir -p "$TMP/r/$(dirname "$d")"; cp "$ROOT/$d" "$TMP/r/$d"; done
}
while IFS='|' read -r file expr; do
  [ -n "$file" ] || continue
  mirror
  python3 -c "import sys; p=sys.argv[1]; s=open(p).read(); t=$expr; open(p,'w').write(t); sys.exit(0 if t!=s else 3)" "$TMP/r/$file" \
    || { echo "  FAIL: mutation did not apply: $file ${expr:0:60}"; FAIL=$((FAIL+1)); continue; }
  if check "$TMP/r" >/dev/null 2>&1; then echo "  FAIL: NOT caught: $file ${expr:0:70}"; FAIL=$((FAIL+1))
  else echo "  PASS: caught: $file ${expr:0:70}"; PASS=$((PASS+1)); fi
done <<MUT
ac_cloud-store/build.json|s.replace('"id": "ipc"', '"id": "ipc-x"')
ac_cloud-store/app/src/main/java/com/diegonmarcos/cloudstore/AccessPage.kt|s.replace('PAGE_IPC -> IpcMeshPage()', 'PAGE_IPC -> PermsList(cloud = true)')
$KT/IpcMeshPage.kt|s.replace('.testTag(row.tag)', '')
$KT/IpcMesh.kt|s.replace('m.endpoints.map { Row(TAG_ENDPOINT + key(m, it), m, it) }', 'm.endpoints.take(1).map { Row(TAG_ENDPOINT + key(m, it), m, it) }')
$KT/IpcMesh.kt|s.replace('installed[m.id] = v', 'installed[m.id] = v; FleetIpc.ping(ctx, m.pkg)')
$LIB/build.gradle|s.replace('bakeB64(ipcMeshB64)', 'bakeB64("")')
aa_cloud-superapp/data/ipc-mesh.json|s.replace('GENERATED by', 'written by hand from')
MUT

echo "== RESULT(#ipc store IPC page): $PASS passed, $FAIL failed =="
[ "$FAIL" -eq 0 ]
