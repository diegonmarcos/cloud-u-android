#!/usr/bin/env bash
# Tester (#571, #779, #803): Cloud ▸ Apps ▸ AGI is exactly Search | AI | Code | Tools |
# MyTerminal | Terminal, SuperApp sits in Configs right before Store, and each launching tile
# LANDS on the app it is named for. (2026-10-13: the B-LLM and S-LLM folders are gone; Tools, the
# Cloud Tools Small LLMs app, took S-LLM's place. test-agi-llm-folders.sh, which pinned the two
# folders, went with them; its A1, AGI right after the row before it, is T0 here; #1092: that row is now Me.)
#
# THE FAILURE THIS EXISTS FOR. #499 pinned the Terminal tile's CAPTION and
# nothing pinned where the tap went: it was app://com.termux.nix with a Play
# Store fallback — the UPSTREAM Nix-on-Droid id, which no fleet build installs —
# so the owner's "Terminal" opened somebody else's store page. MyTerminal named
# the '/files' fork, a separate APK, after #561 made the hub the app. So this
# file resolves every target the way ShellActivity.launchExternalApp does and
# compares the FIRST package it would try with the package the fleet manifest
# (data/constellation-fleet.json, generated by data/regen.sh from each app's own
# build) says that app directory ships. Nothing here names a package id.
#
#   T0  AGI is the tile group immediately after the Me row (#1092)
#   T1  the group's tiles, in order, are the six the owner asked for, with these ids (#803:
#       SuperApp moved out, so AGI starts with Search; 2026-10-14: AI, the Claude bot tile, moved in from Inboxes right after Search; 2026-10-13: no B-LLM, Tools for S-LLM)
#   T2  Search/Tools/Terminal/MyTerminal/Code resolve to ac_cloud-search / ac_cloud-tools-small-llms /
#       ac_cloud-nix-on-droid / ac_cloud-myterminal / ac_cloud-code's own package, and install from
#       that app's release_url (#563 follow-up: Terminal moved from ac_cloud-termux to ac_cloud-nix-on-droid)
#   T3  the Code, Search and Tools glyphs exist as drawables (Sections.iconResFor falls back to
#       ic_link_tile in silence) and are their apps' launcher foregrounds, byte for byte; no AGI tile
#       is a folder any more
#   T4  a not-installed extapp tile draws the #249 placeholder, with strings in
#       every locale, and the install snack is a string resource
#   T5  (#803) the Configs group starts SuperApp | Store — SuperApp immediately before Store —
#       and SuperApp is declared in exactly one tile group under ui.sections
#   T6  (#803) the Search tile declares tint:false (its glyph is the mockup's gradient), the
#       tile parser reads `tint`, and tileCell tints only a missing or tint:true tile
#
# Usage: ./test-agi-tiles.sh   (static only, no network, no device)
set -u
APP="$(cd "$(dirname "$0")/.." && pwd)"          # → aa_cloud-superapp
ROOT="$(cd "$APP/.." && pwd)"
for f in "$APP/build.json" "$APP/data/constellation-fleet.json"; do
  [ -f "$f" ] || { echo "ERROR: $f missing — refusing to report a verdict" >&2; exit 2; }
done
command -v python3 >/dev/null 2>&1 || { echo "ERROR: python3 required" >&2; exit 2; }

python3 - "$APP" "$ROOT" <<'PY'
import json, os, re, sys
app, root = sys.argv[1:3]
passed = failed = 0
def check(cond, msg):
    global passed, failed
    if cond: passed += 1; print("  PASS: " + msg)
    else:    failed += 1; print("  FAIL: " + msg)
def read(p):
    with open(p, encoding="utf-8") as f: return f.read()
def code(p):  # comments stripped, so a doc naming a token cannot satisfy a check
    t = re.sub(r"/\*.*?\*/", "", read(p), flags=re.S)
    return "\n".join(re.sub(r"(?<![:\"])//.*$", "", l) for l in t.splitlines())

bj = json.loads(read(os.path.join(app, "build.json")))
fleet = json.loads(read(os.path.join(app, "data/constellation-fleet.json")))["apps"]
ext = {e["id"]: e for e in bj["ui"]["external_apps"]}

def groups(node, title="AGI"):
    if isinstance(node, dict):
        if (title is None or node.get("title") == title) and isinstance(node.get("tiles"), list) and "title" in node: yield node
        for v in node.values(): yield from groups(v, title)
    elif isinstance(node, list):
        for v in node: yield from groups(v, title)
agi = list(groups(bj["ui"]["sections"]))
check(len(agi) == 1, "exactly one AGI tile group under ui.sections (found %d)" % len(agi))
if len(agi) != 1: print("-- %d passed, %d failed" % (passed, failed)); sys.exit(1)
tiles = agi[0]["tiles"]

print("== T0: AGI sits right after the Me row ==")
cloud = [s for s in bj["ui"]["sections"] if s.get("id") == "cloud"][0]
titles = [g.get("title") for g in cloud.get("tile_groups", [])]
check("AGI" in titles and "Me" in titles and titles.index("AGI") == titles.index("Me") + 1,
      "AGI is the group immediately after Me (%s)" % titles)

print("== T1: the AGI row is the six tiles the owner asked for, in order ==")
got = [t.get("label") for t in tiles]
want = ["Search", "AI", "Code", "Tools", "MyTerminal", "Terminal"]
check(got == want, "AGI captions are %s (want %s)" % (got, want))
ids = [t.get("id") for t in tiles]
check(ids == ["search", "ai-chat", "code", "tools-small-llms", "drive", "ai-tmx"], "AGI tile ids are %s" % ids)
check(not any(t.get("label") in ("B-LLM", "S-LLM") or t.get("id") in ("b-llm", "s-llm") for t in tiles),
      "no B-LLM or S-LLM tile is left in AGI")
check(not any(isinstance(t.get("tiles"), list) for t in tiles), "no AGI tile is a folder")
check((by_label := {t.get("label"): t for t in tiles}).get("Tools", {}).get("target") == "extapp:cloud-tools-small-llms",
      "the Tools tile launches extapp:cloud-tools-small-llms")
by = {t.get("label"): t for t in tiles}
chat = by.get("AI", {})
check(chat.get("id") == "ai-chat" and chat.get("icon") == "ic_ai_chat"
      and chat.get("target", "").startswith("intent://resolve?domain=Cloud_agent_claude_bot#Intent;scheme=tg;"),
      "AI keeps the Claude bot launch target and the ic_ai_chat glyph")
check(os.path.isfile(os.path.join(app, "app/src/main/res/drawable/ic_ai_chat.xml")), "AI's icon is a drawable")
check(bj["ui"].get("retired_tile_ids", {}).get("cloud/ai-tlg-claude") == "cloud/ai-chat",
      "ui.retired_tile_ids maps the old id cloud/ai-tlg-claude to cloud/ai-chat")
check('"cloud/ai-tlg-claude" to "cloud/ai-chat"' in read(os.path.join(app, "app/src/main/java/com/diegonmarcos/superapp/launcher/Sections.kt")),
      "Sections.kt follows the same old -> new tile id")
inbox = list(groups(bj["ui"]["sections"], "Inboxes"))
check(inbox and not any(t.get("id") in ("ai-tlg-claude", "ai-chat") for t in inbox[0]["tiles"]),
      "the AI tile is no longer in Inboxes")

print("== T2: each launching tile resolves to its app's OWN package ==")
def first_candidate(target):
    """ShellActivity.launchExternalApp: fork (if named) → hub → alt; first non-blank."""
    if not target.startswith("extapp:"): return None, None
    appid, _, fork = target[len("extapp:"):].split("#", 1)[0].partition("/")
    e = ext.get(appid)
    if e is None: return None, None
    cands = [(e.get("forks") or {}).get(fork) if fork else None, e.get("hub_package"), e.get("alt_package")]
    return next((c for c in cands if c), None), e
def fleet_for(directory):
    hits = [a for a in fleet if a.get("kind") == "app"
            and a.get("repo_url", "").rstrip("/").endswith("/" + directory)]
    return hits[0] if len(hits) == 1 else None
for label, directory in (("Search", "ac_cloud-search"), ("Tools", "ac_cloud-tools-small-llms"), ("Terminal", "ac_cloud-nix-on-droid"),
                         ("MyTerminal", "ac_cloud-myterminal"), ("Code", "ac_cloud-code")):
    tile, entry = by.get(label), fleet_for(directory)
    check(entry is not None, "fleet manifest has exactly one app built from %s" % directory)
    if tile is None or entry is None: continue
    pkg, e = first_candidate(tile.get("target", ""))
    check(pkg == entry["package"],
          "%s (%s) first launches %r; %s ships %r" % (label, tile.get("target"), pkg, directory, entry["package"]))
    check(e is not None and e.get("install_package") == entry["package"]
          and e.get("install_apk_url") == entry["release_url"],
          "%s installs %s from the fleet's release_url %s" % (label, entry["package"], entry["release_url"]))

def glyph_in(tile, fg):
    # The tile is the plain glyph of the app's generated launcher icon: every
    # path it draws appears verbatim in the launcher foreground.
    tp = re.findall(r'pathData="([^"]+)"', read(tile))
    return bool(tp) and all(('pathData="%s"' % p) in read(fg) for p in tp)

print("== T3: the Code, Search and Tools glyphs exist and are their apps' own launcher foregrounds ==")
for label in ("Search", "Code", "Tools"):
    icon = (by.get(label) or {}).get("icon", "")
    check(bool(icon) and os.path.isfile(os.path.join(app, "app/src/main/res/drawable", icon + ".xml")),
          "%s's icon %r is a drawable in this app (iconResFor would fall back to ic_link_tile in silence)" % (label, icon))
tools_icon = (by.get("Tools") or {}).get("icon", "")
mine = os.path.join(app, "app/src/main/res/drawable", tools_icon + ".xml")
theirs = os.path.join(root, "ac_cloud-tools-small-llms/app/src/main/res/drawable/ic_launcher_foreground.xml")
check(bool(tools_icon) and os.path.isfile(mine) and os.path.isfile(theirs) and glyph_in(mine, theirs),
      "drawable/%s.xml draws ac_cloud-tools-small-llms's launcher glyph (generated: cloud-android-launcher-icons.py)" % tools_icon)
ide_icon = (by.get("Code") or {}).get("icon", "")
mine = os.path.join(app, "app/src/main/res/drawable", ide_icon + ".xml")
theirs = os.path.join(root, "ac_cloud-code/res/android/drawable/ic_launcher_foreground.xml")
check(bool(ide_icon) and os.path.isfile(mine) and os.path.isfile(theirs) and glyph_in(mine, theirs),
      "drawable/%s.xml draws ac_cloud-code's launcher glyph (generated: cloud-android-launcher-icons.py)" % ide_icon)
search_icon = (by.get("Search") or {}).get("icon", "")
mine = os.path.join(app, "app/src/main/res/drawable", search_icon + ".xml")
theirs = os.path.join(root, "ac_cloud-search/app/src/main/res/drawable/ic_launcher_foreground.xml")
check(bool(search_icon) and os.path.isfile(mine) and os.path.isfile(theirs) and read(mine) == read(theirs),
      "drawable/%s.xml is byte-identical to ac_cloud-search's ic_launcher_foreground.xml" % search_icon)

print("== T4: a not-installed extapp tile is the #249 placeholder, localised ==")
kt = os.path.join(app, "app/src/main/java/com/diegonmarcos/superapp")
grouped = code(os.path.join(kt, "launcher/GroupedTilesFragment.kt"))
cell = grouped[grouped.find("internal fun TileCell"):]
cell = cell[:cell.find("\n}\n", 1)]
check("Sections.extappMissing(ctx, tile.target)" in cell, "tileCell asks Sections.extappMissing about its target")
for token in ("R.drawable.ic_app_not_installed", "R.string.phone_app_not_installed_tile_hint",
              "R.string.phone_app_not_installed"):
    # \b: phone_app_not_installed is a prefix of phone_app_not_installed_tile_hint,
    # so a plain substring test passed with the "Not installed" caption deleted.
    check(re.search(re.escape(token) + r"\b", cell), "tileCell draws the placeholder with %s" % token)
sections = code(os.path.join(kt, "launcher/Sections.kt"))
fn = sections[sections.find("fun extappMissing"):]
fn = fn[:fn.find("\n    }") + 6]
check("listOfNotNull(fork, app.hubPackage, app.altPackage)" in fn and "getLaunchIntentForPackage" in fn,
      "extappMissing probes the same fork → hub → alt candidates the dispatcher launches")
shell = code(os.path.join(kt, "ShellActivity.kt"))
launch = shell[shell.find("private fun launchExternalApp"):]
launch = launch[:launch.find("\n    }\n") + 6]
check(not re.search(r'snack\("[^"]*not installed', launch),
      "launchExternalApp's install snacks are string resources, not English literals")
for s in ("phone_install_downloading", "phone_install_no_source"):
    check("R.string." + s in launch, "launchExternalApp snacks R.string.%s" % s)
res = os.path.join(app, "app/src/main/res")
locales = sorted(d for d in os.listdir(res) if d.startswith("values") and os.path.isfile(os.path.join(res, d, "strings.xml")))
check("values" in locales and len(locales) > 1, "found the default and at least one translated strings.xml (%s)" % locales)
for d in locales:
    xml = read(os.path.join(res, d, "strings.xml"))
    for s in ("phone_app_not_installed", "phone_app_not_installed_tile_hint",
              "phone_install_downloading", "phone_install_no_source"):
        check('name="%s"' % s in xml, "%s/strings.xml defines %s" % (d, s))

print("== T5: the Configs row reads SuperApp │ Account │ Store, Controls, Firewall │ C3 │ About ==")
configs = [g for g in groups(bj["ui"]["sections"], "Configs")]
check(len(configs) == 1, "exactly one Configs tile group under ui.sections (found %d)" % len(configs))
if configs:
    row = [t.get("label") for t in configs[0]["tiles"]]
    check(row == ["SuperApp", "|", "Account", "|", "Store", "Controls", "Firewall", "|", "C3", "|", "About"], "Configs row = SuperApp | Account | Store, Controls, Firewall | C3 | About (owner order 2026-10) (got %s)" % row)
    sa = next((t for t in configs[0]["tiles"] if t.get("label") == "SuperApp"), {})
    # #1153 (supersedes #1095): the tile launches the real app as its own task (app://<own package>,
    # NEW_TASK | LAUNCH_ADJACENT in ShellActivity), so split screen keeps the Configs page open beside it.
    check(sa.get("id") == "cloud-superapp" and sa.get("target") == "app://" + bj["android"]["application_id"],
          "the moved SuperApp tile launches the app as its own task (%s)" % sa.get("target"))
holders = [g.get("title") for g in groups(bj["ui"]["sections"], None)
           if any(t.get("id") == "cloud-superapp" for t in g["tiles"])]
check(holders == ["Configs"], "the SuperApp tile is declared once, in Configs (found in %s)" % holders)

print("== T6: the Search tile keeps its gradient ==")
check((by.get("Search") or {}).get("tint") is False, "the Search tile declares tint:false")
check(not any(t.get("tint") is False for t in tiles if t.get("label") != "Search"),
      "no other AGI tile opts out of the tint")
check('tint       = t.optBoolean("tint", true)' in sections, "Sections parses a tile's `tint`, default true")
check(re.search(r"if \(missing\) p\.textSecondary else if \(tile\.tint\) p\.textPrimary else", cell),
      "tileCell tints only a missing tile or one with tint:true")

print("-- test-agi-tiles: %d passed, %d failed" % (passed, failed))
sys.exit(1 if failed else 0)
PY
