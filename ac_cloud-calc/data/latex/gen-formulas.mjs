#!/usr/bin/env node
// Generates the Cloud Calc LaTeX library (assets/latex/formulas.json) from the owner's markdown (100-formulas.md).
//   node gen-formulas.mjs            write the JSON
//   node gen-formulas.mjs --check    fail if the JSON on disk differs from what the markdown yields (drift)
//   node gen-formulas.mjs --render   fail if any formula (or description's inline math) does not render in the bundled KaTeX
// Source shape: `## N. Category`, then per formula `### N. Title`, a one-line `$$...$$` display formula and a description
// paragraph whose inline math stays as `$...$` (the detail view renders it with KaTeX auto-render).
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const SRC = path.join(here, "100-formulas.md");
const OUT = path.join(here, "..", "assets", "latex", "formulas.json");
const KATEX = path.join(here, "..", "assets", "latex", "katex", "katex.min.js");

const slug = (s) => s.toLowerCase().normalize("NFKD").replace(/\$[^$]*\$/g, " ").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");

export function parse(md) {
  const categories = [];
  const formulas = [];
  let cat = null;
  let cur = null;
  for (const raw of md.split(/\r?\n/)) {
    const line = raw.trimEnd();
    let m;
    if ((m = /^## (\d+)\. (.+)$/.exec(line))) {
      cat = { id: slug(m[2]), label: m[2].trim() };
      categories.push(cat);
      cur = null;
    } else if ((m = /^### (\d+)\. (.+)$/.exec(line))) {
      cur = { id: slug(m[2]), number: Number(m[1]), title: m[2].trim(), category: cat.id, latex: "", description: "" };
      formulas.push(cur);
    } else if (cur && (m = /^\$\$(.+)\$\$$/.exec(line))) {
      cur.latex = m[1].trim();
    } else if (cur && line && !line.startsWith("#") && line !== "---") {
      cur.description = (cur.description ? cur.description + " " : "") + line.trim();
    }
  }
  return { categories, formulas };
}

export function build(md) {
  const { categories, formulas } = parse(md);
  return {
    _doc: "GENERATED by data/latex/gen-formulas.mjs from data/latex/100-formulas.md (the owner's library) - edit the markdown, not this file. categories: [{id, label}] in the owner's order; formulas: [{id (unique slug), number, title, category (a category id), latex (the display formula), description (one paragraph; inline math stays as $...$ for KaTeX auto-render)}]. The app adds a 'Mine' category from the user's saved formulas (build.json::latex.mine_category). test/test-calc-latex.sh --check fails if this file drifts from the markdown.",
    version: 1,
    categories,
    formulas,
  };
}

const text = (o) => JSON.stringify(o, null, 1) + "\n";
const arg = process.argv[2];
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const doc = build(fs.readFileSync(SRC, "utf8"));
  const bad = [];
  if (doc.formulas.length !== 100) bad.push(`expected 100 formulas, parsed ${doc.formulas.length}`);
  if (new Set(doc.formulas.map((f) => f.id)).size !== doc.formulas.length) bad.push("duplicate ids");
  doc.formulas.forEach((f, i) => {
    if (f.number !== i + 1) bad.push(`formula ${f.title}: number ${f.number} out of order`);
    if (!f.latex) bad.push(`formula ${f.number} has no $$ formula`);
    if (!f.description) bad.push(`formula ${f.number} has no description`);
  });
  if (arg === "--check") {
    const have = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
    if (have !== text(doc)) bad.push("assets/latex/formulas.json is not what 100-formulas.md generates (run gen-formulas.mjs)");
  } else if (arg === "--render") {
    const katex = createRequire(import.meta.url)(KATEX);
    for (const f of doc.formulas) {
      try { katex.renderToString(f.latex, { throwOnError: true, displayMode: true, trust: false, strict: "ignore" }); }
      catch (e) { bad.push(`formula ${f.number} ${f.title} does not render: ${e.message}`); }
      for (const m of f.description.matchAll(/\$([^$]+)\$/g)) {
        try { katex.renderToString(m[1], { throwOnError: true, strict: "ignore" }); }
        catch (e) { bad.push(`formula ${f.number} description math $${m[1]}$ does not render: ${e.message}`); }
      }
    }
  } else {
    if (!bad.length) fs.writeFileSync(OUT, text(doc));
  }
  if (bad.length) { bad.forEach((b) => console.error("FAIL " + b)); process.exit(1); }
  console.log(`ok: ${doc.formulas.length} formulas, ${doc.categories.length} categories (${arg || "write"})`);
}
