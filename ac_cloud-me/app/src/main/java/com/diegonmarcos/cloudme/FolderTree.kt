package com.diegonmarcos.cloudme

import org.json.JSONObject

/** One folder of the notes vault; [children] are folders too (the tree never holds files). */
data class Folder(val name: String, val path: String, val children: List<Folder>)

/** A separator folder of the vault (0___, 1___, 2___) drawn as a title over the folders it owns. */
data class FolderSection(val title: String, val folders: List<Folder>)

/** One drawn line: a section title, or a folder at [depth] that is [open] or not. */
sealed class FolderRow {
    data class Title(val title: String) : FolderRow()
    data class Item(val folder: Folder, val depth: Int, val open: Boolean) : FolderRow()
}

/**
 * #1350 RoadMap: the folder hierarchy of the notes vault, from data/repos/roadmap-tree.json (generated by
 * data/regen-roadmap-tree.py, schema cloud-me-roadmap-tree/v1). Pure: parse, and flatten into rows under an open set.
 */
object FolderTree {
    const val SCHEMA = "cloud-me-roadmap-tree/v1"

    /** A wrong schema or malformed text is no sections, never a crash. */
    fun parse(text: String): List<FolderSection> = runCatching {
        val o = JSONObject(text)
        if (o.optString("_schema") != SCHEMA) return emptyList()
        o.optJSONArray("sections").objects().map { s -> FolderSection(s.optString("title"), s.optJSONArray("folders").objects().map(::folder)) }
    }.getOrDefault(emptyList())

    private fun folder(o: JSONObject): Folder =
        Folder(o.optString("name"), o.optString("path"), o.optJSONArray("children").objects().map(::folder))

    /** Every section title, then its folders depth-first; a folder's children show only when its path is in [open]. */
    fun rows(sections: List<FolderSection>, open: Set<String>): List<FolderRow> = buildList {
        fun walk(f: Folder, depth: Int) {
            val isOpen = f.path in open && f.children.isNotEmpty()
            add(FolderRow.Item(f, depth, isOpen))
            if (isOpen) f.children.forEach { walk(it, depth + 1) }
        }
        for (s in sections) {
            add(FolderRow.Title(s.title))
            s.folders.forEach { walk(it, 0) }
        }
    }

    /** Every folder path that has children (what Expand all opens). */
    fun containers(sections: List<FolderSection>): Set<String> {
        fun all(f: Folder): List<String> = (if (f.children.isEmpty()) emptyList() else listOf(f.path)) + f.children.flatMap(::all)
        return sections.flatMap { s -> s.folders.flatMap(::all) }.toSet()
    }
}
