#!/usr/bin/env python3
"""RoadMap (#1350): the folder tree of the private notes vault diegonmarcos/cloud-me-pvt-notes.

  data/repos/roadmap-tree.dirs.txt   SNAPSHOT: the vault's `git ls-tree -d -r --name-only main` listing, sorted, hidden
                                     tooling folders already dropped (they are never published)
  data/repos/roadmap-tree.json       GENERATED from the snapshot (DO NOT EDIT), shipped as an asset, drawn by RoadMap > Folders

  ./data/regen-roadmap-tree.py                  render roadmap-tree.json from the snapshot
  ./data/regen-roadmap-tree.py --check          exit 1 if roadmap-tree.json is not the render of the snapshot (drift)
  ./data/regen-roadmap-tree.py --refresh        re-read the vault through `gh api` (git trees, folders only), rewrite the
                                                snapshot, then render; needs a token that can read the private repo
  ./data/regen-roadmap-tree.py --refresh --from-clone <dir>   same, from a local clone (`git ls-tree -d -r`)
  ./data/regen-roadmap-tree.py --check-live     exit 1 if the vault has moved past the snapshot, 0 if current,
                                                3 if the vault cannot be read (CI has no token for a private repo)

Rules, declared here: folders only, never files. A top-level folder named <digits> followed only by underscores is a
SEPARATOR: it becomes a section title and owns the top-level folders whose name starts with "<digits>.". #1367 a
top-level folder named <digits>___<Name> (the vault's parents, 0___Inbox and 1___Workflows) is a PARENT: it becomes a
section titled <Name> that owns its own child folders; it is never drawn as a folder itself. Tooling
folders are hidden with everything under them: HIDDEN names at the top level and any folder whose name starts with a dot.
Ordering is natural (1.9 before 1.10).
"""
import json, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = "diegonmarcos/cloud-me-pvt-notes"
SNAP = os.path.join(HERE, "repos", "roadmap-tree.dirs.txt")
OUT = os.path.join(HERE, "repos", "roadmap-tree.json")
HIDDEN = ("0_docs", "0_hub", "1_workflows", "_dotfiles")
SEP = re.compile(r"^(\d+)_+$")
PARENT = re.compile(r"^(\d+)_{2,}([^_].*)$")


def nat(s):
    return [int(t) if t.isdigit() else t.lower() for t in re.split(r"(\d+)", s)]


def visible(path):
    parts = path.split("/")
    return parts[0] not in HIDDEN and not any(p.startswith(".") for p in parts)


def render(dirs):
    dirs = [d for d in dirs if d and visible(d)]
    kids = {}
    for d in dirs:
        parent = d.rsplit("/", 1)[0] if "/" in d else ""
        kids.setdefault(parent, []).append(d)

    def node(path):
        return {"name": path.rsplit("/", 1)[-1], "path": path,
                "children": [node(c) for c in sorted(kids.get(path, []), key=nat)]}

    top = sorted(kids.get("", []), key=nat)
    seps = [t for t in top if SEP.match(t)]
    sections, owned = [], set()
    for pa in (t for t in top if PARENT.match(t)):
        owned.add(pa)
        sections.append({"title": PARENT.match(pa).group(2).replace("-", " ").replace("_", " "), "separator": pa,
                         "folders": [node(c) for c in sorted(kids.get(pa, []), key=nat)]})
    for sp in seps:
        n = SEP.match(sp).group(1)
        mine = [t for t in top if not SEP.match(t) and t.startswith(n + ".")]
        owned.update(mine)
        sections.append({"title": f"Section {n}", "separator": sp, "folders": [node(t) for t in mine]})
    rest = [t for t in top if not SEP.match(t) and t not in owned]
    if rest:
        sections.append({"title": "Other", "separator": "", "folders": [node(t) for t in rest]})
    return {"_generated": "GENERATED by data/regen-roadmap-tree.py from data/repos/roadmap-tree.dirs.txt — DO NOT EDIT. "
                          "Refresh: ./data/regen-roadmap-tree.py --refresh",
            "_schema": "cloud-me-roadmap-tree/v1", "source": REPO,
            "folder_count": sum(1 for d in dirs if not ("/" not in d and (SEP.match(d) or PARENT.match(d)))), "sections": sections}


def text(tree):
    return json.dumps(tree, indent=2, ensure_ascii=False) + "\n"


def read_snap():
    return [l.rstrip("\n") for l in open(SNAP, encoding="utf-8") if l.strip()]


def live(argv):
    if "--from-clone" in argv:
        d = argv[argv.index("--from-clone") + 1]
        out = subprocess.run(["git", "-C", d, "ls-tree", "-d", "-r", "--name-only", "HEAD"], capture_output=True, text=True, check=True).stdout
        return sorted(l for l in out.splitlines() if l and visible(l))
    r = subprocess.run(["gh", "api", f"repos/{REPO}/git/trees/main?recursive=1",
                        "--jq", '.tree[] | select(.type=="tree") | .path'], capture_output=True, text=True)
    if r.returncode != 0:
        return None
    return sorted(l for l in r.stdout.splitlines() if l and visible(l))


def main(argv):
    if "--check-live" in argv:
        now = live(argv)
        if now is None:
            print(f"SKIP: {REPO} cannot be read here (private repo, no token); the snapshot stays the source. "
                  "Refresh where it can be read: ./data/regen-roadmap-tree.py --refresh")
            return 3
        if now != read_snap():
            print("DRIFT: the vault's folders moved past data/repos/roadmap-tree.dirs.txt — run ./data/regen-roadmap-tree.py --refresh")
            return 1
        print("current: the snapshot matches the vault")
        return 0
    if "--refresh" in argv:
        now = live(argv)
        if now is None:
            print(f"cannot read {REPO} through gh api", file=sys.stderr)
            return 2
        open(SNAP, "w", encoding="utf-8").write("\n".join(now) + "\n")
    want = text(render(read_snap()))
    have = open(OUT, encoding="utf-8").read() if os.path.exists(OUT) else None
    if "--check" in argv:
        if have != want:
            print("DRIFT: data/repos/roadmap-tree.json is not the render of roadmap-tree.dirs.txt — run ./data/regen-roadmap-tree.py "
                  "(or --refresh to re-read the vault first)")
            return 1
        print("roadmap-tree.json is current with its snapshot")
        return 0
    if have != want:
        open(OUT, "w", encoding="utf-8").write(want)
    print("wrote" if have != want else "unchanged", "data/repos/roadmap-tree.json")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
