package com.diegonmarcos.cloudlib.rclone.unison

/**
 * #1084 THE UNISON PROFILE, GENERATED from [UnisonConfig.Pair]; no `.prf` is ever written by hand, and
 * the engine writes this text to its own private dir for the run and deletes it after.
 *
 * Two placeholders are filled by the ENGINE, which owns what they name: `{PORT}` (the loopback port of
 * the SSH bridge, known only once the session is up) and `{BACKUPS}` (the engine's central backup
 * directory for this pair, a private folder of the engine APK).
 *
 * Deliberately absent: sshcmd, servercmd, copyprog, merge and logfile. The engine refuses a profile
 * that names them; the SSH leg is the engine's own bridge, never a command the profile supplies.
 */
object UnisonProfile {
    const val PORT = "{PORT}"
    const val BACKUPS = "{BACKUPS}"

    /** The text of the second root exactly as the profile and `-prefer` must spell it. */
    fun rootB(pair: UnisonConfig.Pair): String = when (val p = pair.peer) {
        // socket://host:port/<path>: an absolute path is spelled with a second slash, as ssh:// does
        is UnisonConfig.Peer.Ssh -> "socket://127.0.0.1:$PORT/" + (if (p.path.startsWith("/")) "/" + p.path.trimStart('/') else p.path)
        is UnisonConfig.Peer.Local -> p.path.trimEnd('/').ifEmpty { "/" }
    }

    /** Both roots as the engine validates `-prefer` against them. */
    fun roots(pair: UnisonConfig.Pair): List<String> = listOf(pair.rootA, rootB(pair))

    fun generate(pair: UnisonConfig.Pair): String = buildString {
        appendLine("# generated by Cloud Drive from data/drive-sync-rules.json unison.pairs[${pair.id}]; do not edit")
        appendLine("root = ${pair.rootA}")
        appendLine("root = ${rootB(pair)}")
        appendLine("batch = ${pair.batch}")
        appendLine("auto = ${pair.auto}")
        appendLine("fastcheck = ${pair.fastcheck}")
        appendLine("times = ${pair.times}")
        // Android shared storage keeps no unix permissions; syncing them only produces false conflicts.
        appendLine("perms = 0")
        // A mass deletion on one side is a thing to look at, never to propagate unattended.
        appendLine("confirmbigdel = true")
        // Archives are named after the machine; the engine fixes UNISONLOCALHOSTNAME so they survive reboots.
        appendLine("backuplocation = central")
        appendLine("backupdir = $BACKUPS")
        if (pair.backup) {
            appendLine("backup = Name *")
            appendLine("maxbackups = ${pair.maxBackups}")
        }
        when (pair.prefer) {
            "a" -> appendLine("prefer = ${pair.rootA}")
            "b" -> appendLine("prefer = ${rootB(pair)}")
            "newer", "older" -> appendLine("prefer = ${pair.prefer}")
        }
        pair.ignore.forEach { appendLine("ignore = $it") }
    }
}
