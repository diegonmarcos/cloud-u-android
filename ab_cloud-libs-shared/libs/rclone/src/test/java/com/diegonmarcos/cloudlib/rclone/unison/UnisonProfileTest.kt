package com.diegonmarcos.cloudlib.rclone.unison

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertTrue
import org.junit.Test

/** #1084 profile generation: the .prf is a pure function of the declaration, never hand-written. */
class UnisonProfileTest {

    private fun pair(extra: String = "", root: String = """{"host":"oci-apps.app","user":"diego","path":"/srv/sync/docs"}""", defaults: String = "{}") =
        UnisonConfig.parse("""{"defaults":$defaults,"ignore":["Name .DS_Store","Name *.tmp","Name build"],"pairs":[{"id":"docs","root_a":"/storage/emulated/0/Sync/Docs"$extra,"root_b":$root}]}""").pairs.single()

    private fun lines(p: UnisonConfig.Pair) = UnisonProfile.generate(p).lines().filter { it.isNotBlank() && !it.startsWith("#") }

    @Test fun anSshPairBridgesTheSecondRootThroughALoopbackSocketWithAnAbsolutePathDoubleSlash() {
        val l = lines(pair())
        assertEquals("root = /storage/emulated/0/Sync/Docs", l[0])
        assertEquals("root = socket://127.0.0.1:{PORT}//srv/sync/docs", l[1])
    }

    @Test fun aRelativePeerPathUsesASingleSlash() {
        assertEquals("root = socket://127.0.0.1:{PORT}/sync/docs", lines(pair(root = """{"host":"oci-apps.app","user":"d","path":"sync/docs"}"""))[1])
    }

    @Test fun aLocalPeerIsItsPlainPath() {
        assertEquals("root = /storage/1234-ABCD/Docs", lines(pair(root = """{"path":"/storage/1234-ABCD/Docs/"}"""))[1])
    }

    @Test fun theDeclaredIgnoreRulesAndOptionsLandVerbatim() {
        val l = lines(pair(""","fastcheck":"true","times":false"""))
        assertTrue("ignore = Name .DS_Store" in l)
        assertTrue("ignore = Name *.tmp" in l)
        assertTrue("ignore = Name build" in l)
        assertTrue("fastcheck = true" in l)
        assertTrue("times = false" in l)
        assertTrue("batch = true" in l && "auto = true" in l)
    }

    @Test fun androidSharedStorageNeverSyncsPermissionsAndAMassDeletionIsAlwaysConfirmed() {
        val l = lines(pair())
        assertTrue("perms = 0" in l)
        assertTrue("confirmbigdel = true" in l)
    }

    @Test fun noPolicyMeansNoPreferLineSoEveryConflictAsks() {
        assertFalse(lines(pair()).any { it.startsWith("prefer") })
    }

    @Test fun policiesMapOntoPreferAndAlwaysKeepBackups() {
        val a = lines(pair(""","prefer":"a""""))
        assertTrue("prefer = /storage/emulated/0/Sync/Docs" in a)
        assertTrue("backup = Name *" in a)
        val b = lines(pair(""","prefer":"b""""))
        assertTrue("prefer = socket://127.0.0.1:{PORT}//srv/sync/docs" in b)
        assertTrue("prefer = newer" in lines(pair(""","prefer":"newer"""")))
        assertTrue("prefer = older" in lines(pair(""","prefer":"older"""")))
    }

    @Test fun backupsGoToTheEnginesCentralDirAndAreCapped() {
        val l = lines(pair(""","max_backups":3"""))
        assertTrue("backuplocation = central" in l)
        assertTrue("backupdir = {BACKUPS}" in l)
        assertTrue("backup = Name *" in l)
        assertTrue("maxbackups = 3" in l)
    }

    @Test fun theProfileNeverNamesACommandOrALogFile() {
        val text = UnisonProfile.generate(pair(""","prefer":"newer""""))
        for (k in listOf("sshcmd", "servercmd", "rshcmd", "sshargs", "copyprog", "merge", "diff", "logfile", "include", "source"))
            assertFalse("the profile must not set $k", Regex("(?m)^\\s*$k\\s*=").containsMatchIn(text))
    }

    @Test fun theProfileSaysItIsGeneratedAndFromWhichPair() {
        val first = UnisonProfile.generate(pair()).lines().first()
        assertTrue(first.startsWith("# generated by Cloud Drive") && first.contains("unison.pairs[docs]") && first.contains("do not edit"))
    }

    @Test fun rootsAreWhatThePreferValuesAreCheckedAgainst() {
        assertEquals(listOf("/storage/emulated/0/Sync/Docs", "socket://127.0.0.1:{PORT}//srv/sync/docs"), UnisonProfile.roots(pair()))
    }

    @Test fun generationIsDeterministic() {
        assertEquals(UnisonProfile.generate(pair()), UnisonProfile.generate(pair()))
    }
}
