package com.diegonmarcos.cloudlib.rclone.engine

import java.io.File
import java.util.UUID
import java.util.concurrent.ConcurrentHashMap
import java.util.concurrent.TimeUnit

/**
 * Runs the pinned static Unison in this process for a client that owns the pair declaration (#1084).
 *
 * WHAT THIS ENGINE KEEPS: Unison's archives (what each replica looked like after the last
 * sync; they are what makes the sync two-way and stateful rather than a mirror), in
 * `<home>` = this APK's private files dir, never shared storage. The profile is the client's: it
 * arrives as text with every call, is written to `<home>/<name>.prf` for the run and is generated by the
 * client from Cloud Drive's declarative config, never hand-written.
 *
 * INTERRUPTED RUNS ARE SAFE. Before a run the archive files are copied to `<home>/.snapshot`; a run
 * that is cancelled, times out or ends fatally (exit 3, or no exit at all) has its archives put back
 * from that copy, so a half-written archive can never make the next run believe the replicas agree.
 * Stale lock and temp files of a killed run are removed before the next one starts. Unison itself
 * writes an archive only once the run completes, so the rollback is the belt over its braces.
 *
 * Pure JVM (binary, dirs and env are handed in), so the suite runs it against a fake binary.
 */
internal class UnisonExec(
    private val binary: File,
    private val home: File,
    private val env: () -> Map<String, String>,
) {
    val isAvailable: Boolean get() = binary.isFile

    /** A running pair sync: lines (stdout and stderr merged) readable by index, like [RcloneExec.Job]. */
    class Job(val id: String, val profile: String) {
        private val lock = Any()
        private val lines = ArrayDeque<String>()
        private var first = 0
        @Volatile var done = false; private set
        @Volatile var rc = -1; private set
        @Volatile var cancelled = false; private set
        @Volatile var rolledBack = false; private set
        internal var process: Process? = null

        internal fun add(line: String) = synchronized(lock) {
            lines.addLast(line)
            while (lines.size > MAX_LINES) { lines.removeFirst(); first++ }
        }

        fun read(cursor: Int, limit: Int = POLL_LINES): Pair<List<String>, Int> = synchronized(lock) {
            val from = maxOf(cursor, first)
            val end = minOf(first + lines.size, from + limit)
            (from until end).map { lines[it - first] } to end
        }

        internal fun finish(code: Int, back: Boolean) { rc = code; rolledBack = back; done = true }
        fun cancel() { cancelled = true; process?.destroy() }
    }

    /** What the client asked for: the generated profile text, the validated extra flags, and the SSH leg to bridge, if any. */
    class Run(val profile: String, val profileText: String, val extra: List<String>, val roots: List<String>, val bridge: (() -> Bridged)?)

    /** A bridge that is up: [port] replaces `{PORT}` in the profile; [close] ends the SSH session. */
    class Bridged(val port: Int, val close: () -> Unit)

    private val jobs = ConcurrentHashMap<String, Job>()

    fun job(id: String): Job? = jobs[id]
    fun forget(id: String) { jobs.remove(id) }
    fun running(profile: String): Boolean = jobs.values.any { it.profile == profile && !it.done }

    private val snapshotDir get() = File(home, ".snapshot")

    private fun archiveFiles(dir: File): List<File> =
        dir.listFiles { f -> f.isFile && ARCHIVE.matches(f.name) }?.toList().orEmpty()

    /** Locks and temp files only a killed run leaves behind. Never an archive. */
    internal fun clearStale() {
        home.listFiles { f -> f.isFile && (f.name.startsWith("lk") || f.name.startsWith("tmp.") || f.name.endsWith(".tmp")) }?.forEach { it.delete() }
    }

    internal fun snapshot() {
        snapshotDir.deleteRecursively(); snapshotDir.mkdirs()
        archiveFiles(home).forEach { it.copyTo(File(snapshotDir, it.name), overwrite = true) }
    }

    /** Put the archives back as [snapshot] saw them: files written since are removed, files lost are restored. */
    internal fun rollback() {
        archiveFiles(home).forEach { it.delete() }
        snapshotDir.listFiles()?.forEach { it.copyTo(File(home, it.name), overwrite = true) }
    }

    private fun writeProfile(name: String, text: String) {
        val f = File(home, "$name.prf")
        val tmp = File(home, "$name.prf.new")
        tmp.writeText(text)
        if (!tmp.renameTo(f)) { f.writeText(text); tmp.delete() }
    }

    /** Start a run; returns at once. The caller polls [Job.read] and finally reads [Job.rc]. */
    fun start(run: Run): Job {
        home.mkdirs()
        val job = Job(UUID.randomUUID().toString(), run.profile)
        jobs[job.id] = job
        Thread {
            var bridged: Bridged? = null
            var ok = false
            try { synchronized(runLock) {
                job.add("[engine] unison ${run.profile}: starting")
                clearStale()
                snapshot()
                val up = run.bridge?.invoke()
                bridged = up
                val port = up?.port?.toString()
                val text = if (port != null) run.profileText.replace("{PORT}", port) else run.profileText
                writeProfile(run.profile, text)
                val extra = if (port == null) run.extra else run.extra.map { it.replace("{PORT}", port) }
                val cmd = listOf(binary.absolutePath, run.profile, "-batch", "-ui", "text") + extra
                val pb = ProcessBuilder(cmd).redirectErrorStream(true).directory(home)
                pb.environment().putAll(env())
                val p = pb.start()
                job.process = p
                if (job.cancelled) p.destroy()
                p.inputStream.bufferedReader().forEachLine { job.add(it) }
                val finished = p.waitFor(RUN_GRACE_S, TimeUnit.SECONDS)
                val code = if (finished) p.exitValue() else { p.destroyForcibly(); -1 }
                val interrupted = job.cancelled || code !in 0..2
                if (interrupted) rollback()
                job.finish(if (job.cancelled) -2 else code, interrupted)
                ok = true
            } } catch (t: Throwable) {
                if (!job.cancelled) job.add("engine: ${t.message ?: t.javaClass.simpleName}")
                runCatching { rollback() }
                job.finish(if (job.cancelled) -2 else -1, true)
            } finally {
                runCatching { bridged?.close?.invoke() }
                runCatching { File(home, "${run.profile}.prf").delete() }
                if (!ok && !job.done) job.finish(-1, true)
            }
        }.apply { isDaemon = true; start() }
        return job
    }

    companion object {
        /** Unison's archive and fingerprint files: `ar`/`fp` + 32 hex of the roots' hash. A profile named ar* is not one. */
        private val ARCHIVE = Regex("(ar|fp)[0-9a-f]{32}")
        /** One run at a time: archives are snapshotted and rolled back as a set, and a killed run's locks are cleared. */
        private val runLock = Any()
        const val MAX_LINES = 5000
        const val POLL_LINES = 400
        const val RUN_GRACE_S = 30L
    }
}
